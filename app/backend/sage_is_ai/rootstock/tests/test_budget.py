"""Rootstock line budget (docs/rootstock/design.md, layout and budgets).

Caps are limits, not targets. Shape from CleanRoom tests/test_budget.py.
"""

from __future__ import annotations

import re
from pathlib import Path

try:
    from .linecount import count
except ImportError:  # run as a script
    from linecount import count

PKG = Path(__file__).resolve().parents[1]
DESIGN = PKG.parents[3] / "docs" / "rootstock" / "design.md"
COUNTED = {".py", ".html", ".js"}
UNCOUNTED = {"tests", "migrations", "generated"}

# Per concept, from the plan's ontology; they sum to 13,860 and the total binds first.
CONCEPTS = {
    "project": 480, "ops": 1150, "config": 760, "identity": 1750,
    "conversations": 2700, "providers": 1550, "privacy": 300, "receipts": 470,
    "knowledge": 1300, "sprigs": 520, "workshop": 1400, "federation": 230,
    "diagnostics": 210, "jobs": 170, "compat": 220, "shell": 650,
}
BUDGET: dict[str, int] = {}  # per-file caps, set after the Phase 0 survey
ADAPTED: dict[str, tuple[str, int]] = {}  # path -> (source@ref, counted lines when adopted)
TOTAL = 13_000
CEILING = 15_000
INIT_CAP = 30
ADAPTED_TOTAL = 5_000
GENERATED_BANNER = "Generated by STARTR-django-code"


def _rel(path: Path) -> str:
    return path.relative_to(PKG).as_posix()


def _sources() -> list[str]:
    return sorted(_rel(p) for p in PKG.rglob("*") if p.is_file() and p.suffix in COUNTED
                  and not set(Path(_rel(p)).parts[:-1]) & UNCOUNTED)


def _cap(rel: str) -> int | None:
    if rel in BUDGET:
        return BUDGET[rel]
    if rel in ADAPTED:
        return None
    if rel.endswith("__init__.py"):
        return INIT_CAP
    raise AssertionError(f"{rel} is not in BUDGET, ADAPTED or an __init__.py")


def _counted() -> dict[str, int]:
    return {rel: count(PKG / rel) for rel in _sources() if _cap(rel) is not None}


def test_every_source_is_budgeted() -> None:
    for rel in _sources():
        _cap(rel)


def test_each_file_within_cap() -> None:
    over = [f"{rel}: {n} > {_cap(rel)}" for rel, n in _counted().items() if n > _cap(rel)]
    assert not over, "over budget: " + ", ".join(over)


def test_each_concept_within_cap() -> None:
    sums: dict[str, int] = {}
    for rel, n in _counted().items():
        concept = rel.split("/")[0] if "/" in rel else ""
        sums[concept] = sums.get(concept, 0) + n
    over = [f"{c or '<root>'}: {n} > {CONCEPTS.get(c, 0)}"
            for c, n in sums.items() if c and n > CONCEPTS.get(c, 0)]
    assert not over, "concept over cap (or not in the ontology): " + ", ".join(over)


def test_total_within_budget() -> None:
    assert TOTAL <= CEILING
    total = sum(_counted().values())
    raised = [int(n.replace(",", "")) for n, _ in re.findall(
        r"Budget raised to ([\d,]+) on (\d{4}-\d{2}-\d{2})",
        DESIGN.read_text() if DESIGN.exists() else "")]
    limit = max([TOTAL, *[r for r in raised if r <= CEILING]])
    assert total <= limit, f"budget: {total}/{limit} lines; raise only by a dated design line"
    print(f"budget: {total}/{limit} lines across {len(_counted())} files")


def test_adapted_files_carry_their_provenance() -> None:
    notice = (PKG / "NOTICE").read_text() if (PKG / "NOTICE").exists() else ""
    problems, total = [], 0
    for rel, (source, adopted) in ADAPTED.items():
        path = PKG / rel
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:3])
        n = count(path)
        total += n
        if f"Adapted from {source}" not in head:
            problems.append(f"{rel}: header must say 'Adapted from {source}'")
        if rel not in notice:
            problems.append(f"{rel}: missing from rootstock/NOTICE")
        if n > adopted * 1.10:
            problems.append(f"{rel}: grew {n - adopted} lines past adoption; budget it instead")
    assert total <= ADAPTED_TOTAL, f"adapted lines {total} > {ADAPTED_TOTAL}"
    assert not problems, "; ".join(problems)


def test_uncounted_folders_hold_only_what_they_claim() -> None:
    """Hand-written code cannot hide in generated/ or migrations/."""
    bad = []
    for path in PKG.rglob("*.py"):
        parts = set(path.relative_to(PKG).parts[:-1])
        text = path.read_text(encoding="utf-8")
        if "generated" in parts and GENERATED_BANNER not in text[:500]:
            bad.append(f"{_rel(path)}: no '{GENERATED_BANNER}' banner")
        if "migrations" in parts and path.name != "__init__.py" and "class Migration(" not in text:
            bad.append(f"{_rel(path)}: not a Django migration")
    for path in PKG.rglob("generated/*"):
        if path.is_file() and path.suffix in {".html", ".js"} and GENERATED_BANNER not in path.read_text()[:500]:
            bad.append(f"{_rel(path)}: no '{GENERATED_BANNER}' banner")
    assert not bad, "; ".join(bad)


if __name__ == "__main__":
    for name, fn in list(globals().items()):
        if name.startswith("test_"):
            fn()
    print("budget tests: ok")
